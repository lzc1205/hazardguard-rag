# 宁可让用例判不出（退化为召回不足），也不能写入错误期望值——
# 错误的期望值会让 CI 把正确实现判成回归。
UNRESOLVED: dict[str, str] = {
    "第八项": (
        "dc_001 问「需要专家论证的规模标准」，但官方附件2 拆除工程分两项"
        "（一）码头桥梁烟囱等易燃易爆拆除、（二）文物保护建筑等拆除，"
        "旧数据未区分子项，无法确定指向哪一项。不做推测映射。"
    ),
}


def _normalize(clause: str) -> str:
    """去掉规范号前缀与空白，只留条款本体。

    评测集里的期望值有两种写法：
        「建办质〔2018〕31号 第三项」  ← 带规范号前缀
        「第三项」                    ← 裸条款号
    两者指同一条，必须归一后才能匹配映射表。

    归一后为空的情况要保留**原样**而不是空串：
    「建办质〔2018〕31号」这种「只有规范号、没有项号」的笼统引用
    若归一成 ''，会既匹配不到映射表、又在集合判断里被当成空值，
    结果是既改不了也发现不了问题。
    """
    c = clause.strip()
    for prefix in ("建办质〔2018〕31号", "建办质[2018]31号", "住建部令第37号"):
        if c.startswith(prefix):
            rest = c.replace(prefix, "").strip()
            if rest:
                return rest
            # 只有规范号、无项号：返回带空格的原串，避免归一成空
            return c
    return c


def map_clause(clause: str) -> str | None:
    """把旧编号映射为官方编号；不在映射表内则返回 None（保持原值）。

    两次尝试：先按**原串**精确匹配（覆盖「建办质〔2018〕31号」这类
    只有规范号、无项号的笼统引用），再按归一化结果匹配
    （覆盖「第三项」与「建办质〔2018〕31号 第三项」两种写法）。
    """
    raw = clause.strip()
    if raw in CLAUSE_ALIAS:
        return CLAUSE_ALIAS[raw]
    return CLAUSE_ALIAS.get(_normalize(clause))


def is_mappable(clause: str) -> bool:
    """判断某条款是否属于可映射范围。

    JGJ / GB 系列属工程建设行业标准，不在本映射内——
    它们的原文需从标准化平台另行获取，且现行版本号可能已更新，
    不适合在缺少原文的情况下写死映射。
    """
    if "JGJ" in clause or "GB" in clause:
        return False
    return map_clause(clause) is not None