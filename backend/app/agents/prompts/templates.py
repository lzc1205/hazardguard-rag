def render(name: str, **kwargs) -> str:
    """渲染 Prompt 模板。

    **为什么不用 str.format**：
    Prompt 里经常要写 JSON 输出格式示例（`{"参数名": "值"}`），
    format 会把 `{"参数名"` 当成占位符并抛 KeyError——
    这不是假设，是写document_extract 模板时真实踩到的。

    所以改成「只替换已声明变量」的安全替换：
    - 声明过的 `{name}` 才会被替换
    - 其余花括号原样保留（JSON、代码示例都不受影响）
    """
    entry = PROMPT_REGISTRY.get(name)
    if entry is None:
        raise KeyError(f"未注册的 Prompt：{name}")

    template = entry["template"]
    missing = [v for v in entry["variables"] if v not in kwargs]
    if missing:
        raise ValueError(f"Prompt '{name}' 缺少变量：{missing}")

    result = template
    for var in entry["variables"]:
        result = result.replace("{" + var + "}", str(kwargs[var]))

    # 声明过的占位符必须全部替换掉，否则说明模板写错了变量名
    leftovers = [
        m for m in re.findall(r"\{(\w+)\}", result)
        if m not in entry["variables"]
    ]
    if leftovers:
        raise ValueError(
            f"Prompt '{name}' 含未声明的占位符：{sorted(set(leftovers))}"
        )

    return result


def get_prompt(name: str) -> dict:
    entry = PROMPT_REGISTRY.get(name)
    if entry is None:
        raise KeyError(f"未注册的 Prompt：{name}")
    return dict(entry)


